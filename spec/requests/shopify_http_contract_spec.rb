# frozen_string_literal: true

require "rails_helper"

# The Shopify specs elsewhere replace the GraphQL client with FakeShopifyAdmin and
# assert only variables. Here the REAL ShopifyAPI client runs and only the HTTP
# endpoint is stubbed (WebMock), so the request on the wire is asserted: URL,
# X-Shopify-Access-Token header, GraphQL operation (name + shape) and variables.
# The stubbed RESPONSE drives the code path (the invoice URL is what the user is
# sent to).
RSpec.describe "Shopify Admin GraphQL over real HTTP (WebMock)", type: :request do
  let(:invoice_url) { "https://shop.example.test/invoices/http-1" }
  let(:draft_id) { "gid://shopify/DraftOrder/7001" }

  before { prime_shopify_context! }

  # Hygiene: the real shpat_/shppa_ token in config/credentials.yml.enc must never reach a
  # spec (WebMock diffs print request headers into CI logs).
  it "runs against the fake Shopify credentials, never the real token" do
    expect(Rails.application.credentials.dig(:test, :shopify, :password) == "shpat_test_fake").to be(true) # boolean: a failure must not print the real token
    expect(Rails.application.credentials[:test][:shopify][:password] == "shpat_test_fake").to be(true)
    expect(ShopifyAPI::Context.api_version).to eq("2025-01")
    expect(ShopifyAPI::Context.active_session.access_token == "shpat_test_fake").to be(true)
    expect(ShopifyAPI::Context.active_session.shop).to eq("fake-shop.myshopify.com")
  end

  describe "membership draft order (POST /memberships)" do
    let(:user) { create(:user, :regular_user) }
    let!(:tier) do
      create(:membership_tier, title_en: "1 Semester Membership", title_fr: "Adhesion 1 semestre",
                               duration: 120, internal_price: 25, external_price: 40)
    end

    it "creates the draft order then fetches its invoice URL, and redirects the user to it" do
      creates = stub_draft_order_create(draft_id)
      fetches = stub_draft_order_fetch(draft_id, invoice_url: invoice_url)
      shop_log_in!(user)

      expect { post memberships_path, params: { membership: { membership_tier_id: tier.id } } }
        .to change(Membership, :count).by(1)

      membership = Membership.last
      expect(response).to have_http_status(:found)
      expect(response.location).to eq(invoice_url)
      expect(membership.shopify_draft_order_id).to eq(draft_id)

      expect(creates.size).to eq(1)
      create = creates.first
      expect_shopify_auth(create)
      expect(create[:body]["query"]).to include("mutation draftOrderCreate($input: DraftOrderInput!)")
      expect(create[:body]["query"]).to include("draftOrderCreate(input: $input)")
      expect(create[:body]["variables"]).to eq(
        "input" => {
          "note" => "Generated by makerepo",
          "tags" => ["makerepo_test_membership"],
          "lineItems" => [{ "originalUnitPrice" => "40.0", "quantity" => 1, "title" => "1 Semester Membership" }],
          "metafields" => [{ "namespace" => "makerepo", "key" => "membership_db_reference",
                             "value" => membership.id.to_s, "type" => "number_integer" }]
        }
      )

      expect(fetches.size).to eq(1)
      fetch = fetches.first
      expect_shopify_auth(fetch)
      expect(fetch[:body]["query"]).to include("query getDraftOrder($id: ID!)")
      expect(fetch[:body]["query"]).to include("invoiceUrl")
      expect(fetch[:body]["variables"]).to eq("id" => draft_id)
    end

    it "when Shopify answers userErrors over HTTP: the pending row is destroyed and the page 500s (WART D-S23)" do
      stub_shopify_graphql("mutation draftOrderCreate", { "draftOrderCreate" => { "draftOrder" => nil,
                           "userErrors" => [{ "field" => ["input"], "message" => "boom" }] } })
      shop_log_in!(user)
      post memberships_path, params: { membership: { membership_tier_id: tier.id } }
      # WART(D-S23): the failure path renders :index without its ivars, so the intended alert page is a 500
      expect(response).to have_http_status(:internal_server_error)
      expect(response.location).to be_nil
      expect(Membership.count).to eq(0)
    end
  end

  describe "locker draft order (LockerRental#checkout_link)" do
    let(:size) { create(:locker_size, shopify_gid: "gid://shopify/ProductVariant/55") }
    let(:locker) { create(:locker, locker_size: size) }
    let!(:rental) { create(:locker_rental, :await_payment, locker: locker) }

    def run_checkout
      creates = stub_draft_order_create(draft_id)
      fetches = stub_draft_order_fetch(draft_id, invoice_url: invoice_url)
      link = rental.checkout_link
      [link, creates, fetches]
    end

    it "sends the TEST free line item outside production, and returns the invoice URL from the response" do
      link, creates, fetches = run_checkout

      expect(link).to eq(invoice_url)
      expect(rental.reload.shopify_draft_order_id).to eq(draft_id)
      expect(creates.size).to eq(1)
      expect(fetches.size).to eq(1)
      expect_shopify_auth(creates.first)
      expect(creates.first[:body]["query"]).to include("mutation draftOrderCreate($input: DraftOrderInput!)")
      expect(creates.first[:body]["variables"]).to eq(
        "input" => {
          "note" => "Generated by makerepo",
          "tags" => ["makerepo_test_locker"],
          "lineItems" => [{ "quantity" => 1, "title" => "TEST locker on test environment.",
                            "originalUnitPriceWithCurrency" => { "amount" => "0", "currencyCode" => "CAD" } }],
          "metafields" => [{ "namespace" => "makerepo", "key" => "locker_db_reference",
                             "value" => rental.id.to_s, "type" => "number_integer" }]
        }
      )
      expect_shopify_auth(fetches.first)
      expect(fetches.first[:body]["variables"]).to eq("id" => draft_id)
    end

    # M28: the only branch that runs in production.
    it "in production sends the real variant (locker.locker_size.shopify_gid) with the production tag" do
      allow(Rails.env).to receive(:production?).and_return(true)
      link, creates, = run_checkout

      expect(link).to eq(invoice_url)
      expect(creates.first[:body]["variables"]).to eq(
        "input" => {
          "note" => "Generated by makerepo",
          "tags" => ["makerepo_locker"],
          "lineItems" => [{ "quantity" => 1, "variantId" => "gid://shopify/ProductVariant/55" }],
          "metafields" => [{ "namespace" => "makerepo", "key" => "locker_db_reference",
                             "value" => rental.id.to_s, "type" => "number_integer" }]
        }
      )
      expect(LockerRental.draft_order_operating_tag).to eq("makerepo_locker")
    end

    it "the production line item follows the rental's locker size (not a constant)" do
      allow(Rails.env).to receive(:production?).and_return(true)
      other = create(:locker, locker_size: create(:locker_size, shopify_gid: "gid://shopify/ProductVariant/99"))
      rental.update_column(:locker_id, other.id)
      expect(rental.reload.send(:shopify_draft_order_line_items))
        .to eq([{ quantity: 1, variantId: "gid://shopify/ProductVariant/99" }])
    end

    it "does not call Shopify for a rental that is not awaiting payment" do
      rental.update_column(:state, "active")
      expect(rental.reload.checkout_link).to be_nil
      expect(a_request(:post, shopify_graphql_url)).not_to have_been_made
    end
  end

  describe "job-order payment link (JobOrder#checkout_link)" do
    include JobOrderSpecHelpers

    before { seed_job_types! }

    let(:order) { create(:job_order, user: create(:user, :regular_user)) }

    it "creates the draft order with the fee line items and returns the fetched invoice URL" do
      order.job_tasks.create!(title: "Task #1").tap do |task|
        task.build_job_task_quote(price: 20, service_price: 3, service_quantity: 2).save!
      end
      creates = stub_draft_order_create(draft_id)
      fetches = stub_draft_order_fetch(draft_id, invoice_url: invoice_url)

      expect(order.reload.checkout_link).to eq(invoice_url)

      expect(order.reload.shopify_draft_order_id).to eq(draft_id)
      expect_shopify_auth(creates.first)
      expect(creates.first[:body]["query"]).to include("mutation draftOrderCreate($input: DraftOrderInput!)")
      expect(creates.first[:body]["variables"]).to eq(
        "input" => {
          "note" => "Generated by makerepo",
          "tags" => ["makerepo_test_job_order"],
          "lineItems" => [
            { "quantity" => 1, "title" => "Task #1 Service Fee",
              "originalUnitPriceWithCurrency" => { "amount" => "20.0", "currencyCode" => "CAD" } },
            { "quantity" => 1, "title" => "Task #1 Parts Fee",
              "originalUnitPriceWithCurrency" => { "amount" => "6.0", "currencyCode" => "CAD" } },
            { "quantity" => 1, "title" => "Line Items Total",
              "originalUnitPriceWithCurrency" => { "amount" => "0.0", "currencyCode" => "CAD" } }
          ],
          "metafields" => [{ "namespace" => "makerepo", "key" => "job_order_db_reference",
                             "value" => order.id.to_s, "type" => "number_integer" }]
        }
      )
      expect_shopify_auth(fetches.first)
      expect(fetches.first[:body]["variables"]).to eq("id" => draft_id)
    end
  end

  it "ShopifyAPI::Context.setup has a single call site: ShopifyContext.ensure_setup!" do
    callers = Dir[Rails.root.join("{app,lib,config}/**/*.rb")].select { |f| File.read(f).include?("ShopifyAPI::Context.setup") }
                  .map { |f| Pathname(f).relative_path_from(Rails.root).to_s }
    expect(callers).to eq(["lib/shopify_context.rb"])
  end

  it "every Shopify session start and the boot initializer go through ShopifyContext.ensure_setup!" do
    %w[app/services/shopify_service.rb app/models/concerns/shopify_concern.rb
       app/models/concerns/shopify_cart_concern.rb config/initializers/shopify_api.rb].each do |file|
      expect(File.read(Rails.root.join(file))).to include("ShopifyContext.ensure_setup!"), file
    end
  end

  describe "in a fresh process (nothing but the boot initializer ran Context.setup)" do
    # Regression for D-S36-new: ShopifyConcern.start_shopify_session never calls
    # Context.setup, so the API version comes from config/initializers/shopify_api.rb.
    # Simulated by blanking the Context, then re-running the initializer.
    let(:context_ivars) { %i[@api_key @api_secret_key @api_version @host] }

    def blank_context!
      context_ivars.each { |iv| ShopifyAPI::Context.instance_variable_set(iv, iv == :@host ? nil : "") }
    end

    def membership_for_checkout
      tier = create(:membership_tier, duration: 30, internal_price: 1, external_price: 2)
      create(:membership, user: create(:user, :regular_user), membership_tier: tier, status: "pending")
    end

    around do |example|
      saved = context_ivars.to_h { |iv| [iv, ShopifyAPI::Context.instance_variable_get(iv)] }
      example.run
    ensure
      saved.each { |iv, v| ShopifyAPI::Context.instance_variable_set(iv, v) }
    end

    it "posts the draft order to /admin/api/<configured version>/graphql.json" do
      blank_context!
      expect(ShopifyAPI::Context.api_version).to eq("")
      load Rails.root.join("config/initializers/shopify_api.rb")

      creates = stub_draft_order_create(draft_id)
      stub_draft_order_fetch(draft_id, invoice_url: invoice_url)
      expect(membership_for_checkout.checkout_link).to eq(invoice_url)

      expect(creates.size).to eq(1)
      expect(creates.first[:url]).to eq("https://fake-shop.myshopify.com/admin/api/2025-01/graphql.json")
      expect(ShopifyAPI::Context.api_version).to eq("2025-01")
    end

    it "heals a failed boot setup: the next draft order still goes to the versioned URL" do
      blank_context!
      allow(Rails.error).to receive(:report)
      allow(Rails.application.credentials).to receive(:dig).with(:test, :shopify)
                                                            .and_return(ShopifyHttpHelpers::FAKE_SHOPIFY_CONFIG.merge(api_key: nil))
      load Rails.root.join("config/initializers/shopify_api.rb") # boot setup fails (api_key missing), no raise
      expect(ShopifyAPI::Context.api_version).to eq("")
      allow(Rails.application.credentials).to receive(:dig).with(:test, :shopify)
                                                            .and_return(ShopifyHttpHelpers::FAKE_SHOPIFY_CONFIG)

      creates = stub_draft_order_create(draft_id)
      stub_draft_order_fetch(draft_id, invoice_url: invoice_url)
      expect(membership_for_checkout.checkout_link).to eq(invoice_url)
      expect(creates.first[:url]).to eq("https://fake-shop.myshopify.com/admin/api/2025-01/graphql.json")
    end

    it "a missing api_key reports and does not raise at boot" do
      reported = []
      allow(Rails.error).to receive(:report) { |e, **| reported << e }
      allow(Rails.application.credentials).to receive(:dig).with(:test, :shopify)
                                                            .and_return(ShopifyHttpHelpers::FAKE_SHOPIFY_CONFIG.merge(api_key: nil))
      expect { load Rails.root.join("config/initializers/shopify_api.rb") }.not_to raise_error
      expect(reported.map(&:class)).to eq([ShopifyContext::MissingConfig])
    end
  end
end
