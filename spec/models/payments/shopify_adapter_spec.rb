# frozen_string_literal: true

require "rails_helper"

# The Shopify adapter against Shopify stubbed at the HTTP boundary (WebMock): the REAL ShopifyAPI client runs, so what
# goes on the wire is asserted. The operations it wraps must be byte-for-byte the requests the app sends today.
RSpec.describe Payments::ShopifyAdapter do
  include ShopifyWebhookHelpers
  include ActiveSupport::Testing::TimeHelpers

  let(:adapter) { described_class.new }
  let(:provider_name) { "shopify" }
  let(:gid) { "gid://shopify/DraftOrder/8001" }
  let(:invoice_url) { "https://shop.example.test/invoices/pay-1" }

  before { prime_shopify_context! }

  # Answers the GraphQL POSTs whose query contains `marker` with `body`; returns the raw request bodies, in order.
  def answer(marker, body, status: 200)
    seen = []
    stub_request(:post, shopify_graphql_url)
      .with { |req| JSON.parse(req.body)["query"].include?(marker) && seen << req.body }
      .to_return(status: status, body: body.to_json, headers: ShopifyHttpHelpers::JSON_HEADERS)
    seen
  end

  def draft(status) = { "data" => { "draftOrder" => { "id" => gid, "name" => "#D1", "invoiceUrl" => invoice_url, "status" => status } } }

  def refused_delete = { "data" => { "draftOrderDelete" => { "deletedId" => nil, "userErrors" => [{ "field" => nil, "message" => "no" }] } } }

  # The delete answer and the getDraftOrder answer of a draft in each state.
  def checkout_in(state)
    deleted = { "data" => { "draftOrderDelete" => { "deletedId" => gid, "userErrors" => [] } } }
    answer("mutation draftOrderDelete", state == :open ? deleted : refused_delete)
    answer("query getDraftOrder", {
      open: draft("OPEN"), stuck: draft("OPEN"), paid: draft("COMPLETED"),
      gone: { "data" => { "draftOrder" => nil } },
      unanswered: { "errors" => [{ "message" => "Throttled", "extensions" => { "code" => "THROTTLED" } }], "data" => nil }
    }.fetch(state))
    gid
  end

  def arrange_create
    @creates = answer("mutation draftOrderCreate",
                      { "data" => { "draftOrderCreate" => { "draftOrder" => { "id" => gid, "invoiceUrl" => invoice_url }, "userErrors" => [] } } })
  end

  def arrange_create_refused
    answer("mutation draftOrderCreate",
           { "data" => { "draftOrderCreate" => { "draftOrder" => nil, "userErrors" => [{ "field" => ["input"], "message" => "boom" }] } } })
  end

  def expect_provider_received(lines:, reference:)
    expect(@creates.size).to eq(1)
    expect(JSON.parse(@creates.first)["variables"]).to eq(
      "input" => {
        "note" => "Generated by makerepo",
        "tags" => ["makerepo_test_locker", "locker_rental:#{reference.record_id}", "makerepo_test_checkout_#{reference.checkout_id}"],
        "lineItems" => JSON.parse(lines.to_json),
        "metafields" => [{ "namespace" => "makerepo", "key" => "locker_db_reference", "value" => reference.record_id.to_s,
                           "type" => "number_integer" }]
      }
    )
  end

  def listing(*nodes) = answer("query paymentsOpenCheckout", { "data" => { "draftOrders" => { "nodes" => nodes } } })

  def node(id, status, tags) = { "id" => id, "status" => status, "tags" => tags, "invoiceUrl" => "https://shop.example.test/invoices/#{id[/\d+\z/]}" }

  def arrange_open_checkout(reference)
    tag = "makerepo_test_checkout_#{reference.checkout_id}"
    listing(node("gid://shopify/DraftOrder/1", "COMPLETED", [tag]),
            node("gid://shopify/DraftOrder/2", "OPEN", ["makerepo_test_checkout_#{reference.checkout_id}0"]),
            node("gid://shopify/DraftOrder/3", "INVOICE_SENT", ["makerepo_test_locker", tag]))
    Payments::Checkout.new(id: "gid://shopify/DraftOrder/3", pay_url: "https://shop.example.test/invoices/3")
  end

  def arrange_no_open_checkout(_reference) = listing

  def shopify_request(body, hmac:, topic: "orders/paid")
    headers = { "CONTENT_TYPE" => "application/json", "HTTP_X_SHOPIFY_TOPIC" => topic, "HTTP_X_SHOPIFY_HMAC_SHA256" => hmac }.compact
    request = ActionDispatch::Request.new(Rack::MockRequest.env_for("/custom_webhooks/orders_paid", method: "POST", input: body, **headers))
    { body: request.raw_post, headers: request.headers } # what CustomWebhooksController passes
  end

  def signed(hook, topic: "orders/paid", secret: shopify_webhook_secret)
    body = hook.to_json
    shopify_request(body, hmac: shopify_hmac_for(body, secret: secret), topic: topic)
  end

  def webhook(signature, provider_ref:, references:, amount:, paid_at:, cash: false)
    raise ArgumentError, "a card payment of one product" if cash || references.size != 1

    reference = references.first
    body = { id: provider_ref.to_i, total_price: amount.to_s, processed_at: paid_at.iso8601,
             tags: "makerepo_test_locker, locker_rental:#{reference.record_id}, makerepo_test_checkout_#{reference.checkout_id}" }.to_json
    hmac = { valid: shopify_hmac_for(body), none: nil, wrong: shopify_hmac_for(body, secret: "another") }.fetch(signature)
    shopify_request(body, hmac: hmac)
  end

  def unsupported_topic_webhook = signed({ id: 1 }, topic: "orders/create")

  def malformed_webhook = signed({ name: "#1001" })

  it_behaves_like "a Payments adapter"

  describe "the operations it wraps send exactly what the app sends today" do
    let(:pinned_get_draft_order) do
      <<~QUERY
        query getDraftOrder($id: ID!) {
          draftOrder(id: $id) {
            id
            name
            invoiceUrl
            status
            tags
            lineItems(first: 1) {
              nodes {
                originalUnitPriceSet {
                  shopMoney {
                    amount
                  }
                }
              }
            }
            order {
              id
              fullyPaid
              displayFinancialStatus
            }
            metafields(first: 10) {
              nodes {
                key
                value
                type
              }
            }
          }
        }
      QUERY
    end
    let(:pinned_draft_order_delete) do
      <<~QUERY
        mutation draftOrderDelete($input: DraftOrderDeleteInput!) {
          draftOrderDelete(input: $input) {
            deletedId
            userErrors {
              field
              message
            }
          }
        }
      QUERY
    end
    let(:pinned_draft_order_create) do
      <<~QUERY
        mutation draftOrderCreate($input: DraftOrderInput!) {
          draftOrderCreate(input: $input) {
            draftOrder {
              id
              invoiceUrl
            }
            userErrors {
              field
              message
            }
          }
        }
      QUERY
    end

    it "checkout_status sends the getDraftOrder query of Payments::ShopifyAdapter::DraftOrders.fetch_result" do
      sent = answer("query getDraftOrder", draft("OPEN"))
      Payments::ShopifyAdapter::DraftOrders.fetch_result(gid)
      adapter.checkout_status(gid)

      expect(sent.size).to eq(2)
      expect(sent.last).to eq(sent.first)
      expect(JSON.parse(sent.last)).to eq("query" => pinned_get_draft_order, "variables" => { "id" => gid })
    end

    it "cancel_checkout sends the draftOrderDelete of Payments::ShopifyAdapter::DraftRemoval, then its check after a refusal" do
      deletes = answer("mutation draftOrderDelete", refused_delete)
      fetches = answer("query getDraftOrder", draft("OPEN"))
      expect(Payments::ShopifyAdapter::DraftRemoval.call(gid).outcome).to eq(:open)
      expect(adapter.cancel_checkout(gid)).to eq(:failed)

      expect([deletes.size, fetches.size]).to eq([2, 2])
      expect([deletes.last, fetches.last]).to eq([deletes.first, fetches.first])
      expect(JSON.parse(deletes.last)).to eq("query" => pinned_draft_order_delete, "variables" => { "input" => { "id" => gid } })
      expect(JSON.parse(fetches.last)).to eq("query" => pinned_get_draft_order, "variables" => { "id" => gid })
    end

    describe "create_checkout sends the draftOrderCreate of the model's own checkout" do
      before { arrange_create }

      def expect_same_create(record)
        reference = Payments::Reference.new(kind: record.class.shopify_draft_order_key_name, record_id: record.id)
        old_id, = record.send(:create_remote_draft_order)
        checkout = adapter.create_checkout(lines: record.send(:shopify_draft_order_line_items), reference: reference)

        expect(checkout).to eq(Payments::Checkout.new(id: old_id, pay_url: invoice_url))
        expect(@creates.size).to eq(2)
        expect(@creates.last).to eq(@creates.first)
        expect(JSON.parse(@creates.last)["query"]).to eq(pinned_draft_order_create)
        JSON.parse(@creates.last)["variables"]
      end

      it "for a membership (no marker tag)" do
        tier = create(:membership_tier, title_en: "1 Semester Membership", duration: 120, internal_price: 25, external_price: 40)
        membership = create(:membership, user: create(:user, :regular_user), membership_tier: tier, status: "pending")

        expect(expect_same_create(membership)).to eq(
          "input" => {
            "note" => "Generated by makerepo",
            "tags" => ["makerepo_test_membership"],
            "lineItems" => [{ "originalUnitPrice" => "40.0", "quantity" => 1, "title" => "1 Semester Membership" }],
            "metafields" => [{ "namespace" => "makerepo", "key" => "membership_db_reference",
                               "value" => membership.id.to_s, "type" => "number_integer" }]
          }
        )
      end

      it "for a locker rental (operating tag and rental marker)" do
        rental = create(:locker_rental, :await_payment)
        expect(expect_same_create(rental)["input"]["tags"]).to eq(["makerepo_test_locker", "locker_rental:#{rental.id}"])
      end

      it "for a job order (operating tag and order marker)" do
        order = create(:job_order, user: create(:user, :regular_user))
        expect(expect_same_create(order)["input"]["tags"]).to eq(["makerepo_test_job_order", "job_order:#{order.id}"])
      end
    end

    it "uses the models' kinds and marker names" do
      expect(Payments::ShopifyAdapter::Order::TAGGED_KINDS).to eq([LockerRental, Membership, JobOrder].map(&:shopify_draft_order_key_name))
      expect(Payments::Reference::KINDS).to eq(Payments::ShopifyAdapter::Order::TAGGED_KINDS + ["cc_money"])
      expect(described_class::MARKERS).to eq("locker" => LockerRental.draft_marker_name, "job_order" => JobOrder.draft_marker_name)
      expect { Membership.draft_marker_name }.to raise_error(NotImplementedError)
    end
  end

  describe "#create_checkout" do
    it "raises on an HTTP answer that is not 200, and on an answer without the draft" do
      answer("mutation draftOrderCreate", {}, status: 202)
      reference = Payments::Reference.new(kind: "membership", record_id: 1)
      expect { adapter.create_checkout(lines: [], reference: reference) }.to raise_error(RuntimeError, /Received HTTP 202/)

      WebMock.reset!
      answer("mutation draftOrderCreate", { "data" => { "draftOrderCreate" => { "draftOrder" => nil, "userErrors" => [] } } })
      expect { adapter.create_checkout(lines: [], reference: reference) }.to raise_error(RuntimeError, /No draft order data/)
    end
  end

  describe "#checkout_status" do
    it "lets an HTTP error status from the client propagate" do
      answer("query getDraftOrder", {}, status: 500)
      expect { adapter.checkout_status(gid) }.to raise_error(ShopifyAPI::Errors::HttpResponseError)
    end

    it "lets a 200 answer whose body is not a JSON object raise, never reading it as gone or unknown" do
      stub_request(:post, shopify_graphql_url).to_return(status: 200, body: "[1]", headers: ShopifyHttpHelpers::JSON_HEADERS)
      expect { Payments::ShopifyAdapter::DraftOrders.fetch_result(gid) }.to raise_error(TypeError)
      stub_request(:post, shopify_graphql_url).to_return(status: 200, body: '"x"', headers: ShopifyHttpHelpers::JSON_HEADERS)
      expect { Payments::ShopifyAdapter::DraftOrders.fetch_result(gid) }.to raise_error(NoMethodError)
    end

    it "is :unknown for a 2xx answer other than 200" do
      answer("query getDraftOrder", {}, status: 202)
      expect(adapter.checkout_status(gid)).to eq(:unknown)
    end

    it "is :unknown for a draft in a status that is neither payable nor paid" do
      answer("query getDraftOrder", draft("SOMETHING_NEW"))
      expect(adapter.checkout_status(gid)).to eq(:unknown)
    end
  end

  describe "#find_open_checkout" do
    let(:reference) { Payments::Reference.new(kind: "locker", record_id: 42, checkout_id: 7) }

    it "sends one paymentsOpenCheckout search for the payable drafts with the checkout tag" do
      sent = listing
      adapter.find_open_checkout(reference: reference)

      expect(JSON.parse(sent.first)).to eq(
        "query" => <<~GRAPHQL,
          query paymentsOpenCheckout($query: String!, $first: Int!) {
            draftOrders(first: $first, query: $query, sortKey: ID) {
              nodes {
                id
                status
                tags
                invoiceUrl
              }
            }
          }
        GRAPHQL
        "variables" => { "query" => "(status:open OR status:invoice_sent) tag:makerepo_test_checkout_7", "first" => 10 }
      )
    end

    it "reads a comma-separated tag string" do
      listing(node("gid://shopify/DraftOrder/4", "OPEN", "makerepo_test_locker, makerepo_test_checkout_7"))
      expect(adapter.find_open_checkout(reference: reference).id).to eq("gid://shopify/DraftOrder/4")
    end

    it "raises when Shopify does not answer the search" do
      answer("query paymentsOpenCheckout", { "errors" => [{ "message" => "Throttled" }] })
      expect { adapter.find_open_checkout(reference: reference) }.to raise_error(RuntimeError, /No draftOrders/)

      WebMock.reset!
      answer("query paymentsOpenCheckout", {}, status: 202)
      expect { adapter.find_open_checkout(reference: reference) }.to raise_error(RuntimeError, /Received HTTP 202/)
    end
  end

  describe "#parse_webhook" do
    def rejection(request)
      adapter.parse_webhook(**request)
    rescue Payments::WebhookRejected => e
      e.reason
    end

    it "keys the event as ProcessedOrder stores the order, for both topics and both id spellings" do
      expect(adapter.parse_webhook(**signed({ id: 900 })).provider_ref).to eq(ProcessedOrder.ref_for("900", "orders/paid"))
      expect(adapter.parse_webhook(**signed({ admin_graphql_api_id: "gid://shopify/Order/901" })).provider_ref).to eq("901")
      expect(adapter.parse_webhook(**signed({ id: 902 }, topic: "orders/fulfilled")).provider_ref).to eq("902/fulfilled")
    end

    it "takes paid_at from the latest fulfillment of a cash order, else the time it is read" do
      travel_to(Time.zone.parse("2026-11-05 10:00:00")) do
        hook = { id: 1, fulfillments: [{ created_at: "2026-11-03T09:00:00-05:00" }, { created_at: "2026-11-04T09:00:00-05:00" }, "x"] }
        expect(adapter.parse_webhook(**signed(hook, topic: "orders/fulfilled")).paid_at).to eq(Time.zone.parse("2026-11-04T09:00:00-05:00"))
        expect(adapter.parse_webhook(**signed({ id: 1 }, topic: "orders/fulfilled")).paid_at).to eq(Time.current)
        expect(adapter.parse_webhook(**signed({ id: 1, processed_at: "nonsense" })).paid_at).to eq(Time.current)
      end
    end

    it "reads the references from this environment's tags only" do
      membership = adapter.parse_webhook(**signed({ id: 1, tags: ["makerepo_test_membership", "makerepo_test_checkout_3"] }))
      expect(membership.references).to eq([Payments::Reference.new(kind: "membership", record_id: nil, checkout_id: 3)])
      expect(adapter.parse_webhook(**signed({ id: 1, tags: "makerepo_locker, locker_rental:5" })).references).to eq([])
      expect(adapter.parse_webhook(**signed({ id: 1 })).references).to eq([])
      two_markers = adapter.parse_webhook(**signed({ id: 1, tags: "makerepo_test_locker, locker_rental:5, locker_rental:6" }))
      expect(two_markers.references).to eq([Payments::Reference.new(kind: "locker")])
    end

    it "names every product of an order, tagged kinds in their order and CC Money last" do
      hook = { id: 1, tags: "makerepo_test_membership, makerepo_test_job_order, job_order:4, makerepo_test_locker, locker_rental:5",
               line_items: [{ product_id: 1 }, "x", { product_id: Payments::ShopifyAdapter::Order::CC_PRODUCT_ID.to_s }] }
      event = adapter.parse_webhook(**signed(hook))
      expect(event.kinds).to eq(%w[locker membership job_order cc_money])
      expect(event.references.map(&:record_id)).to eq([5, nil, 4, nil])
      expect(adapter.parse_webhook(**signed({ id: 1, line_items: [{ product_id: 1 }] })).references).to eq([])
    end

    it "marks an orders/fulfilled delivery as a cash payment" do
      expect(adapter.parse_webhook(**signed({ id: 1 }, topic: "orders/fulfilled")).cash).to be(true)
      expect(adapter.parse_webhook(**signed({ id: 1 })).cash).to be(false)
    end

    # The order's own tags decide the routing: a value that is neither a string nor a list (Shopify sends one of the
    # two) names no product, as the routing has always read it (ShopifyAdapter.tag_list).
    it "reads tags sent as a comma-separated string or a list, and names nothing for tags of any other shape" do
      expect(adapter.parse_webhook(**signed({ id: 1, tags: " makerepo_test_locker ,locker_rental:5" })).references)
        .to eq([Payments::Reference.new(kind: "locker", record_id: 5)])
      expect(adapter.parse_webhook(**signed({ id: 1, tags: ["makerepo_test_locker", "locker_rental:5"] })).references)
        .to eq([Payments::Reference.new(kind: "locker", record_id: 5)])
      [{ "makerepo_test_locker" => "locker_rental:5" }, 5, nil, true].each do |tags|
        expect(adapter.parse_webhook(**signed({ id: 1, tags: tags })).references).to eq([]), tags.inspect
      end
    end

    it "keeps an unreadable or missing amount as nil" do
      expect(adapter.parse_webhook(**signed({ id: 1, total_price: "12,50" })).amount).to be_nil
      expect(adapter.parse_webhook(**signed({ id: 1, total_price: "Infinity" })).amount).to be_nil
      expect(adapter.parse_webhook(**signed({ id: 1 })).amount).to be_nil
      expect(adapter.parse_webhook(**signed({ id: 1, total_price: "40.005" })).amount).to eq(BigDecimal("40.01"))
    end

    it "accepts the old secret during a rotation" do
      rotating = described_class.new(webhook_secrets: ["", "new-secret", "old-secret"])
      expect(rotating.parse_webhook(**signed({ id: 1 }, secret: "old-secret")).provider_ref).to eq("1")
    end

    it "rejects every request when no secret is configured" do
      unconfigured = described_class.new(webhook_secrets: [nil, ""])
      expect { unconfigured.parse_webhook(**signed({ id: 1 })) }
        .to raise_error(Payments::WebhookRejected) { |e| expect(e.reason).to eq(:not_configured) }
    end

    it "rejects a topic it does not turn into a payment, and a body that is no order" do
      expect(rejection(signed({ id: 1 }, topic: "orders/create"))).to eq(:unsupported_topic)
      expect(rejection(signed({ id: 1 }, topic: nil))).to eq(:unsupported_topic)
      expect(rejection(signed({ name: "#1001" }))).to eq(:malformed)
      expect(rejection(signed([1, 2]))).to eq(:malformed)
      body = "not json"
      expect(rejection(shopify_request(body, hmac: shopify_hmac_for(body)))).to eq(:malformed)
    end
  end
end
