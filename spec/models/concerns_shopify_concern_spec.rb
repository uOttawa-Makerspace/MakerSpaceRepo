# frozen_string_literal: true

require "rails_helper"

# ShopifyConcern as used by Membership (has the draft-order column), JobOrder,
# LockerRental, PriceRule and DiscountCode (REST session only). The GraphQL
# client is replaced by ShopSpecHelpers::FakeShopifyAdmin; nothing opens a socket.
RSpec.describe ShopifyConcern do
  let(:user) { create(:user, :regular_user) }
  let(:tier) { create(:membership_tier, title_en: "Day", duration: 1, external_price: 5) }
  let(:membership) { create(:membership, user: user, membership_tier: tier, status: "pending") }
  let!(:fake) { stub_shopify_admin! }

  before { block_external_http! }

  describe ".target_tag / .draft_order_operating_tag" do
    it "uses makerepo_<env> outside production" do
      expect(ShopifyConcern.target_tag).to eq("makerepo_test")
      expect(Membership.draft_order_operating_tag).to eq("makerepo_test_membership")
      expect(JobOrder.draft_order_operating_tag).to eq("makerepo_test_job_order")
      expect(LockerRental.draft_order_operating_tag).to eq("makerepo_test_locker")
    end

    it "uses the bare 'makerepo' tag in production" do
      allow(Rails.env).to receive(:production?).and_return(true)
      expect(ShopifyConcern.target_tag).to eq("makerepo")
    end

    it "raises NotImplementedError for models that include the concern but do not name a draft key" do
      expect { PriceRule.draft_order_operating_tag }.to raise_error(NotImplementedError)
      expect { DiscountCode.shopify_draft_order_key_name }.to raise_error(NotImplementedError)
    end
  end

  describe ".draft_order_processable?" do
    let(:tag) { Membership.draft_order_operating_tag }

    it "accepts arrays and comma-separated strings, trimming whitespace" do
      expect(Membership.draft_order_processable?([tag])).to be(true)
      expect(Membership.draft_order_processable?("a,  #{tag} ,b")).to be(true)
      expect(Membership.draft_order_processable?([:"#{tag}"])).to be(true)
    end

    it "rejects other tags, nil and other types; matching is exact and case-sensitive" do
      expect(Membership.draft_order_processable?(["makerepo_membership"])).to be(false)
      expect(Membership.draft_order_processable?(tag.upcase)).to be(false)
      expect(Membership.draft_order_processable?("x#{tag}")).to be(false)
      expect(Membership.draft_order_processable?(nil)).to be(false)
      expect(Membership.draft_order_processable?(123)).to be(false)
      expect(Membership.draft_order_processable?({ a: tag })).to be(false)
    end
  end

  describe ".start_shopify_session" do
    it "activates a session for <shop_name>.myshopify.com from the env credentials" do
      cfg = Rails.application.credentials.dig(:test, :shopify) || {}
      session = Membership.start_shopify_session
      expect(session.shop).to eq("#{cfg[:shop_name]}.myshopify.com")
      expect(ShopifyAPI::Context.active_session).to eq(session)
    end
  end

  describe "draft order lifecycle" do
    it "creates the draft on first use with tag, line items and a db-reference metafield, stores its id, then fetches it" do
      result = membership.send(:shopify_draft_order)
      expect(result["invoiceUrl"]).to eq(fake.invoice_url)
      expect(membership.reload.shopify_draft_order_id).to eq(fake.draft_id)
      expect(fake.calls.map { |c| c[:query][/\b(draftOrderCreate|getDraftOrder)\b/] }).to eq(%w[draftOrderCreate getDraftOrder])
      input = fake.calls.first[:variables][:input]
      expect(input[:note]).to eq("Generated by makerepo")
      expect(input[:tags]).to eq(["makerepo_test_membership"])
      expect(input[:metafields]).to eq([{ namespace: "makerepo", key: "membership_db_reference", value: membership.id.to_s, type: "number_integer" }])
    end

    it "only fetches when the draft already exists (no second create)" do
      membership.update_column(:shopify_draft_order_id, fake.draft_id)
      membership.send(:shopify_draft_order)
      expect(fake.calls.map { |c| c[:query] }.none? { |q| q.include?("draftOrderCreate") }).to be(true)
    end

    it "raises on a non-200 create, on userErrors and on a missing draft payload" do
      fake.status = 502
      expect { membership.send(:shopify_draft_order) }.to raise_error(/Network error: Received HTTP 502/)
      fake.status = 200
      fake.user_errors = [{ "message" => "bad tax" }, { "message" => "bad line" }]
      expect { membership.send(:shopify_draft_order) }.to raise_error("Shopify Draft Order Creation Failed: bad tax, bad line")
      expect(membership.reload.shopify_draft_order_id).to be_nil
    end

    it "returns nil when fetching answers non-200" do
      membership.update_column(:shopify_draft_order_id, fake.draft_id)
      fake.status = 500
      expect(membership.send(:fetch_shopify_draft_order)).to be_nil
      expect(membership.shopify_is_paid).to be(false)
    end

    it "destroy_shopify_draft_order deletes remotely and clears the id; false when there is none" do
      expect(membership.send(:destroy_shopify_draft_order)).to be(false)
      membership.update_column(:shopify_draft_order_id, fake.draft_id)
      expect(membership.send(:destroy_shopify_draft_order)).to be(true)
      expect(membership.reload.shopify_draft_order_id).to be_nil
    end

    it "destroy keeps the id and returns false on a non-200 response" do
      membership.update_column(:shopify_draft_order_id, fake.draft_id)
      fake.status = 500
      expect(membership.send(:destroy_shopify_draft_order)).to be(false)
      expect(membership.reload.shopify_draft_order_id).to eq(fake.draft_id)
    end

    it "refuses to run on a model without the shopify_draft_order_id column" do
      expect { PriceRule.new.send(:ensure_can_use_draft_order) }
        .to raise_error(RuntimeError, "Model PriceRule does not define a shopify_draft_order_id column")
      expect { DiscountCode.new.send(:shopify_draft_order) }
        .to raise_error(RuntimeError, /does not define a shopify_draft_order_id column/)
    end
  end

  describe "#draft_order_metafields" do
    it "returns the node metafields for a gid, [] for a blank gid, and uses the record's draft id by default" do
      fake.metafields = [{ "namespace" => "makerepo", "key" => "membership_db_reference", "value" => "7" }]
      expect(membership.send(:draft_order_metafields, "gid://shopify/Order/1"))
        .to eq([{ "namespace" => "makerepo", "key" => "membership_db_reference", "value" => "7" }])
      expect(membership.send(:draft_order_metafields, "")).to eq([])
      expect(membership.send(:draft_order_metafields)).to eq([]) # no draft id yet
      membership.update_column(:shopify_draft_order_id, fake.draft_id)
      expect(membership.send(:draft_order_metafields).size).to eq(1)
      expect(fake.calls.last[:variables]).to eq({ ownerId: fake.draft_id })
    end
  end
end
